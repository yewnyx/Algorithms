    /// <summary>
    /// A cell's place along a Hilbert curve through a cube of 1024 cells a side, from its place
    /// along the Morton curve through the same cube.
    /// </summary>
    /// <remarks>
    /// Cells that follow one another along a Hilbert curve always share a face, where a Morton
    /// curve jumps: a run of the curve is a compact lump of space. The curve is Skilling's
    /// ("Programming the Hilbert curve", 2004), with x's bit the highest of each three.
    /// Going down from the top, each level is one bit of each coordinate, an octant. The digit
    /// the curve gives an octant depends on the octant and on which way round the curve lies
    /// there, which the levels above decide: one of 24 states. The table holds, for each state and
    /// each two levels of the Morton key, the two digits and the state that follows. It was made
    /// from the plain computation and gives the same key for every one of the 2^30 cells.
    /// Whole numbers only, so every runtime gives the same key. On a managed runtime the table is
    /// an array allocated once, about 3 KB, when the key is first asked for.
